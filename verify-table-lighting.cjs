const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=__dirname;
const settings=fs.readFileSync(path.join(root,'table-scene-kit/settings.js'),'utf8');
const scene=fs.readFileSync(path.join(root,'table-scene-kit/table-scene.js'),'utf8');
const room=fs.readFileSync(path.join(root,'table-scene-kit/vendor/RoomEnvironment.js'),'utf8');
const glb=fs.readFileSync(path.join(root,'table-scene-kit/table_p.glb'));
const json=JSON.parse(glb.subarray(20,20+glb.readUInt32LE(12)).toString());
assert.ok(json.materials.some(material=>material.pbrMetallicRoughness),'GLB contains PBR materials');
assert.match(settings,/exposure: 0\.80/);
assert.match(settings,/environmentIntensity: 0\.38/);
for(const [name,value] of [['ambient','0.32'],['key','0.45'],['fill','0.10'],['shadowRadius','2.5']])assert.match(settings,new RegExp(name+': '+value.replace('.','\\.')));
assert.match(scene,/scene\.environment=environment\.texture/);
assert.match(scene,/scene\.environmentIntensity=settings\.environmentIntensity/);
assert.match(room,/from '\.\/three\.module\.js'/);
assert.ok(!scene.includes('new THREE.MeshLambertMaterial'),'The GLB materials must stay intact');
assert.match(scene,/THREE\.PCFShadowMap/);
assert.match(scene,/key\.shadow\.mapSize\.set\(2048,2048\)/);
assert.match(scene,/key\.shadow\.normalBias=span\*\.00035/);
assert.match(scene,/key\.shadow\.bias=-0\.00005/);
assert.match(scene,/createRadialGradient\(32,32,0,32,32,32\)/);
for(const [stop,alpha] of [['0','0.65'],['.48','0.35'],['1','0']])assert.ok(scene.includes(`gradient.addColorStop(${stop},'rgba(0,0,0,${alpha})')`));
assert.match(scene,/bounceSize\.x\*1\.45,bounceSize\.z\*1\.45/);
assert.match(scene,/contactMaterial\.opacity=\.72\*\(1-\.88\*lift\)/);
assert.ok(Math.abs(.72*(1-.88)-.0864)<1e-12);
console.log('Table PBR lighting and contact shadows: PASS');
