const assert = require('node:assert/strict');
const {introPose,introLinePose,timeline,modelScrollAnchors}=require('./script.js');
const travel=2040;
assert.equal(introPose(0,travel).progress,0);
const end=introPose(travel,travel);
assert.equal(end.progress,1);
const fs=require('node:fs');
const html=fs.readFileSync(__dirname+'/index.html','utf8');
const css=fs.readFileSync(__dirname+'/styles.css','utf8');
const script=fs.readFileSync(__dirname+'/script.js','utf8');
const modelModule=fs.readFileSync(__dirname+'/intro-model.js','utf8');
assert.match(html,/class="intro-model-stage" data-node-id="738:634"/);
assert.doesNotMatch(html,/class="f02-layer-020/);
assert.doesNotMatch(html,/class="f02-layer-022/);
assert.doesNotMatch(css+script,/--bread-(?:rotation|shift|arrival)/);
assert.match(modelModule,/framing:\{size:438,centerX:1035,centerY:545\}/);
const segments=timeline([1020,3060,1020,1020]);
const anchors=modelScrollAnchors(segments);
assert.deepEqual(anchors,[segments[1].start,segments[1].start+segments[1].entryHold+segments[1].travel,segments[2].start]);
assert.ok(anchors[0]<anchors[1]&&anchors[1]<anchors[2]);
for(const name of ['tws.glb','tws_w.glb']){
  const glb=fs.readFileSync(__dirname+'/assets/tws-model-kit/'+name);
  assert.equal(glb.toString('ascii',0,4),'glTF');
  assert.equal(glb.readUInt32LE(4),2);
  assert.equal(glb.readUInt32LE(8),glb.length);
  const gltf=JSON.parse(glb.toString('utf8',20,20+glb.readUInt32LE(12)).trimEnd());
  assert.ok(gltf.meshes?.length>0);
}
assert.match(css,/#intro \.f02-layer-006 \{ left: 301px;/);
assert.match(css,/#intro \.f02-layer-037 \{ top: 319px; transform: translateY\(var\(--intro-offset, 0px\)\)/);
assert.deepEqual(introPose(travel+1500,travel),end,'End pose stays fixed during hold');
assert.deepEqual(introLinePose(0,0,.20,0,true),{opacity:1,y:0});
assert.deepEqual(introLinePose(.5,0,.20,0,true),{opacity:0,y:-40});
const entering=introLinePose(.38,.32,.59,0);
assert.ok(entering.opacity>0&&entering.opacity<1&&entering.y>0,'Enter from below');
assert.ok(introLinePose(.38,.32,.59,1).opacity<entering.opacity,'Lines are staggered');
const leaving=introLinePose(.65,.32,.59,0);
assert.ok(leaving.opacity>0&&leaving.opacity<1&&leaving.y<0,'Exit upward');
for(let line=0;line<4;line++)assert.deepEqual(introLinePose(1,.71,null,line),{opacity:1,y:0});
